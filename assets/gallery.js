/* ==========================================================================
   Gallery + lightbox.
   Reads photos.json (regenerated by tools/build_manifest.py) and renders a
   justified grid. No dependencies, no build step.
   ========================================================================== */

(function () {
  "use strict";

  var grid      = document.getElementById("grid");
  var filterBar = document.querySelector(".filters");
  var lightbox  = document.getElementById("lightbox");
  var lbImage   = lightbox.querySelector(".lb-image");
  var lbTitle   = lightbox.querySelector(".lb-title");
  var lbMeta    = lightbox.querySelector(".lb-meta");
  var lbExif    = lightbox.querySelector(".lb-exif");

  var allPhotos = [];   // everything from the manifest
  var visible   = [];   // current filter result — what the arrows walk through
  var index     = -1;   // position within `visible`
  var isOpen    = false;

  var yearEl = document.getElementById("year");
  if (yearEl) yearEl.textContent = String(new Date().getFullYear());

  /* ---------- helpers ---------------------------------------------- */

  function el(tag, className) {
    var node = document.createElement(tag);
    if (className) node.className = className;
    return node;
  }

  function titleCase(str) {
    return str.replace(/(^|[\s-])(\w)/g, function (_, sep, chr) {
      return sep + chr.toUpperCase();
    });
  }

  // "2026-01-12" -> "12 January 2026". Anything unparseable is passed through
  // untouched, so a freeform date like "Spring 2025" still displays.
  function formatDate(value) {
    if (!value) return "";
    var m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value);
    if (!m) return value;
    var d = new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3]));
    if (isNaN(d.getTime())) return value;
    return d.toLocaleDateString(undefined, {
      day: "numeric", month: "long", year: "numeric"
    });
  }

  function aspectOf(photo) {
    var w = Number(photo.width), h = Number(photo.height);
    if (!w || !h) return 1.5;                 // sane default if dims are missing
    return Math.max(0.4, Math.min(4, w / h)); // clamp so nothing breaks the row
  }

  function altFor(photo) {
    var parts = [photo.title];
    if (photo.location) parts.push("photographed at " + photo.location);
    return parts.filter(Boolean).join(", ") || "Photograph";
  }

  function exifLine(photo) {
    var e = photo.exif;
    if (!e) return "";
    return [e.camera, e.lens, e.focal, e.aperture, e.shutter,
            e.iso ? "ISO " + e.iso : ""]
      .filter(Boolean).join("  ·  ");
  }

  function metaLine(photo) {
    return [photo.location, formatDate(photo.date)].filter(Boolean).join("  ·  ");
  }

  /* ---------- rendering --------------------------------------------- */

  function renderGrid(photos) {
    grid.textContent = "";

    if (!photos.length) {
      var empty = el("p", "grid-status");
      empty.textContent = "No photographs in this category yet.";
      grid.appendChild(empty);
      return;
    }

    var frag = document.createDocumentFragment();

    photos.forEach(function (photo, i) {
      var tile = el("button", "tile");
      tile.type = "button";
      tile.style.setProperty("--ar", aspectOf(photo).toFixed(4));
      tile.setAttribute("aria-label", "View " + (photo.title || "photograph") + " larger");

      var img = el("img");
      img.src = photo.thumb || photo.src;
      img.alt = altFor(photo);
      img.loading = i < 6 ? "eager" : "lazy";  // first row shouldn't fade in late
      img.decoding = "async";
      img.width = photo.width || 0;
      img.height = photo.height || 0;
      img.dataset.loaded = "false";

      var reveal = function () { img.dataset.loaded = "true"; };
      if (img.complete) reveal(); else {
        img.addEventListener("load", reveal, { once: true });
        // A missing file shouldn't leave an invisible hole in the grid.
        img.addEventListener("error", reveal, { once: true });
      }

      var label = el("span", "tile-label");
      var t = el("span", "tile-title");
      t.textContent = photo.title || "";
      label.appendChild(t);

      if (photo.location) {
        var p = el("span", "tile-place");
        p.textContent = photo.location;
        label.appendChild(p);
      }

      tile.appendChild(img);
      tile.appendChild(label);
      tile.addEventListener("click", function () { open(i); });

      frag.appendChild(tile);
    });

    grid.appendChild(frag);
  }

  function renderFilters(photos) {
    var counts = {};
    photos.forEach(function (p) {
      var c = p.category || "other";
      counts[c] = (counts[c] || 0) + 1;
    });

    var cats = Object.keys(counts).sort();
    // A filter bar with one button is just decoration.
    if (cats.length < 2) { filterBar.hidden = true; return; }

    var entries = [{ key: "all", label: "All", count: photos.length }];
    cats.forEach(function (c) {
      entries.push({ key: c, label: titleCase(c), count: counts[c] });
    });

    entries.forEach(function (entry, i) {
      var btn = el("button", "filter-btn");
      btn.type = "button";
      btn.dataset.filter = entry.key;
      btn.setAttribute("aria-pressed", i === 0 ? "true" : "false");
      btn.innerHTML = "";
      btn.appendChild(document.createTextNode(entry.label));
      var count = el("span", "filter-count");
      count.textContent = entry.count;
      btn.appendChild(count);

      btn.addEventListener("click", function () { applyFilter(entry.key); });
      filterBar.appendChild(btn);
    });
  }

  function applyFilter(key) {
    visible = key === "all"
      ? allPhotos.slice()
      : allPhotos.filter(function (p) { return (p.category || "other") === key; });

    Array.prototype.forEach.call(
      filterBar.querySelectorAll(".filter-btn"),
      function (btn) {
        btn.setAttribute("aria-pressed", btn.dataset.filter === key ? "true" : "false");
      }
    );

    renderGrid(visible);
  }

  /* ---------- lightbox ---------------------------------------------- */

  function show(i) {
    if (!visible.length) return;
    // Wrap around at both ends.
    index = (i + visible.length) % visible.length;

    var photo = visible[index];
    lbImage.src = photo.src;
    lbImage.alt = altFor(photo);
    lbTitle.textContent = photo.title || "";
    lbMeta.textContent = metaLine(photo);
    lbExif.textContent = exifLine(photo);

    // Warm the neighbours so arrowing through feels instant.
    [index + 1, index - 1].forEach(function (n) {
      var neighbour = visible[(n + visible.length) % visible.length];
      if (neighbour) { var pre = new Image(); pre.src = neighbour.src; }
    });
  }

  function open(i) {
    show(i);
    if (!isOpen) {
      isOpen = true;
      lightbox.hidden = false;
      document.body.classList.add("lb-open");
      lightbox.querySelector(".lb-close").focus();
      // Lets the phone/browser Back gesture close the viewer.
      try { history.pushState({ lb: true }, ""); } catch (e) { /* file:// */ }
    }
  }

  function close(fromPopstate) {
    if (!isOpen) return;
    isOpen = false;
    lightbox.hidden = true;
    lbImage.removeAttribute("src");
    document.body.classList.remove("lb-open");

    if (!fromPopstate && history.state && history.state.lb) {
      try { history.back(); } catch (e) { /* no-op */ }
    }
  }

  lightbox.querySelector(".lb-close").addEventListener("click", function () { close(false); });
  lightbox.querySelector(".lb-prev").addEventListener("click", function () { show(index - 1); });
  lightbox.querySelector(".lb-next").addEventListener("click", function () { show(index + 1); });

  // Clicking the backdrop closes; clicking the photo or caption doesn't.
  lightbox.addEventListener("click", function (ev) {
    if (ev.target === lightbox || ev.target.classList.contains("lb-figure")) close(false);
  });

  window.addEventListener("popstate", function () { close(true); });

  document.addEventListener("keydown", function (ev) {
    if (!isOpen) return;
    if (ev.key === "Escape")     { close(false); }
    else if (ev.key === "ArrowRight") { show(index + 1); }
    else if (ev.key === "ArrowLeft")  { show(index - 1); }
    else return;
    ev.preventDefault();
  });

  // Swipe between photos on touch devices.
  var touchX = null, touchY = null;
  lightbox.addEventListener("touchstart", function (ev) {
    touchX = ev.changedTouches[0].clientX;
    touchY = ev.changedTouches[0].clientY;
  }, { passive: true });

  lightbox.addEventListener("touchend", function (ev) {
    if (touchX === null) return;
    var dx = ev.changedTouches[0].clientX - touchX;
    var dy = ev.changedTouches[0].clientY - touchY;
    // Horizontal intent only, and long enough not to be a stray tap.
    if (Math.abs(dx) > 45 && Math.abs(dx) > Math.abs(dy)) {
      show(dx < 0 ? index + 1 : index - 1);
    }
    touchX = touchY = null;
  }, { passive: true });

  /* ---------- boot --------------------------------------------------- */

  function fail(message) {
    grid.textContent = "";
    var p = el("p", "grid-status");
    p.textContent = message;
    grid.appendChild(p);
  }

  fetch("photos.json", { cache: "no-cache" })
    .then(function (res) {
      if (!res.ok) throw new Error("HTTP " + res.status);
      return res.json();
    })
    .then(function (data) {
      allPhotos = (data && data.photos) || [];
      if (!allPhotos.length) {
        fail("No photographs yet. Add images to images/ and run tools/build_manifest.py.");
        return;
      }
      renderFilters(allPhotos);
      applyFilter("all");
    })
    .catch(function () {
      // Almost always this: the page was opened as a file:// URL, where fetch
      // is blocked by CORS. Tell them what to actually do about it.
      fail(location.protocol === "file:"
        ? "Open this site through a local web server, not by double-clicking the file. In the project folder run:  python3 -m http.server 8000"
        : "Couldn't load photos.json.");
    });
})();
